import { config } from '../config';
import Replicate from 'replicate';
import fs from 'fs';
import path from 'path';
import sharp from 'sharp';

const STICKER_PROMPT = `A 5x5 grid of 25 cute sticker-style character portraits showing different emotions and expressions. Each portrait features the same person with consistent facial features and identity. Cute vector animation style with smooth outlines, soft shading, and expressive poses. Emotions include: happy, excited, surprised, thinking, angry, sad, crying, laughing, facepalm, embarrassed, sleepy, proud, confused, mischievous, shocked, worried, determined, thumbs up, thumbs down, waving, wink, neutral, OK gesture, heart sign, celebration. Clean white background, uniform framing, cohesive style.`;

export class StickerGeneratorService {
    private replicate: Replicate;

    constructor() {
        this.replicate = new Replicate({
            auth: config.replicateApiToken,
        });
    }

    async generateStickerGrid(imageBuffer: Buffer): Promise<string> {
        try {
            // Compress image before sending to API
            console.log('Preparing image for Replicate...');
            const compressedBuffer = await sharp(imageBuffer)
                .resize(1024, 1024, {
                    fit: 'inside',
                    withoutEnlargement: true,
                })
                .jpeg({ quality: 85 })
                .toBuffer();

            const originalSize = imageBuffer.length;
            const compressedSize = compressedBuffer.length;
            console.log(`Image prepared: ${(originalSize / 1024).toFixed(1)}KB → ${(compressedSize / 1024).toFixed(1)}KB`);

            // Convert to base64 data URL
            const base64Image = compressedBuffer.toString('base64');
            const dataUrl = `data:image/jpeg;base64,${base64Image}`;

            console.log('Calling Replicate SDXL API...');

            // Generate sticker grid using SDXL
            const output = await this.replicate.run(
                'stability-ai/sdxl:39ed52f2a78e934b3ba6e2a89f5b1c712de7dfea535525255b1aa35c5565e08b',
                {
                    input: {
                        image: dataUrl,
                        prompt: STICKER_PROMPT,
                        width: 1024,
                        height: 1024,
                        num_outputs: 1,
                        scheduler: 'K_EULER',
                        num_inference_steps: 30,
                        guidance_scale: 7.5,
                        prompt_strength: 0.8,
                    },
                }
            ) as any;

            // Get the output URL
            const imageUrl = Array.isArray(output) ? output[0] : output;

            if (!imageUrl) {
                throw new Error('No image generated by SDXL');
            }

            console.log('Image generated successfully');

            // Download and save the image
            const imagePath = await this.downloadAndSaveImage(imageUrl);

            return imagePath;
        } catch (error) {
            console.error('Error generating sticker grid:', error);
            throw error;
        }
    }

    private async downloadAndSaveImage(imageUrl: string): Promise<string> {
        // Download the image from URL
        const response = await fetch(imageUrl);

        if (!response.ok) {
            throw new Error(`Failed to download image: ${response.statusText}`);
        }

        const arrayBuffer = await response.arrayBuffer();
        const buffer = Buffer.from(arrayBuffer);

        // Save to temp directory
        const tempDir = path.join(process.cwd(), 'temp');
        if (!fs.existsSync(tempDir)) {
            fs.mkdirSync(tempDir, { recursive: true });
        }

        const filename = `grid_${Date.now()}.png`;
        const filepath = path.join(tempDir, filename);

        await fs.promises.writeFile(filepath, buffer);

        return filepath;
    }
}

export const stickerGeneratorService = new StickerGeneratorService();
